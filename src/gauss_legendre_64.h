// integrate f over y in [0,1].
template <class F>
inline double gauss_legendre_64(F&& f) {
  double sum = 0.0;
  for (int i = 0; i < 64; ++i) {
    const double y = 0.5 * (X64[i] + 1.0);
    sum += W64[i] * f(y);
  }
  return 0.5 * sum;
}

template <class F>
inline double integrate_gl64_ab(double a, double b, F&& f01) {
  // map y in [0,1] to x in [a,b]: x = a + (b-a)*y
  const double w = (b - a);
  if (!(w > 0.0) || !R_finite(w)) return 0.0;
  return w * gauss_legendre_64([&](double y){
    const double x = a + w * y;
    return f01(x);
  });
}
