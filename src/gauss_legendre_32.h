// integrate f over y in [0,1].
template <class F>
inline double gauss_legendre_32(F&& f) {
  double sum = 0.0;
  for (int i = 0; i < 32; ++i) {
    const double y = 0.5 * (X[i] + 1.0);
    sum += W[i] * f(y);
  }
  return 0.5 * sum;
}
